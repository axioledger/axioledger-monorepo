// ─── Size resolver ────────────────────────────────────────────────────────────

const SIZE_MAP: Record<Exclude<AXQIconSize, number>, number> = {
  standard: 20,
  nav:      24,
  large:    32,
}

function resolveSize(sz: AXQIconSize): number {
  if (typeof sz === "number") return sz
  return SIZE_MAP[sz]
}

// ─── Component ────────────────────────────────────────────────────────────────

export const AXQIcon: React.FC<AXQIconProps> = ({
  name,
  // v2 props
  variant,
  size = "nav",
  colorToken = "primary",
  ariaLabel,
  // legacy compat props
  style: legacyStyle,
  color: legacyColor,
  label: legacyLabel,
  className = "",
  ...svgProps
}) => {
  const iconVariant: AXQIconStyle = variant ?? legacyStyle ?? "bold"
  const pxSize = resolveSize(size)
  const effectiveLabel = ariaLabel ?? legacyLabel

  const colorClass = `axq-icon--${colorToken}`
  const combinedClass = ["axq-icon", colorClass, className].filter(Boolean).join(" ")

  const accessibilityProps = effectiveLabel
    ? { "aria-label": effectiveLabel, role: "img" as const }
    : { "aria-hidden": true as const }

  const def = ICONS[name as AXQIconName]

  // ── Branch 1: Inline critical icons (zero network cost) ──────────────────
  if (def) {
    const fill = legacyColor ?? "currentColor"
    return (
      <svg
        width={pxSize}
        height={pxSize}
        viewBox={def.viewBox}
        fill="none"
        xmlns="http://www.w3.org/2000/svg"
        className={combinedClass}
        {...accessibilityProps}
        {...svgProps}
      >
        {def.paths.map((d, i) => (
          <path key={i} d={d} fill={fill} />
        ))}
      </svg>
    )
  }

  // ── Branch 2: SVG Sprite fallback for 1877+ extended icons ───────────────
  // Requires: /icons/axq-sprites.svg built by scripts/build-svg-sprites.mjs
  return (
    <svg
      width={pxSize}
      height={pxSize}
      viewBox="0 0 24 24"
      fill="none"
      xmlns="http://www.w3.org/2000/svg"
      className={combinedClass}
      {...accessibilityProps}
      {...svgProps}
    >
      <use href={`/icons/axq-sprites.svg#${name}-${iconVariant}`} />
    </svg>
  )
}

AXQIcon.displayName = "AXQIcon"
