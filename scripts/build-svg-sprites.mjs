#!/usr/bin/env node
/**
 * build-svg-sprites.mjs
 *
 * Đóng gói toàn bộ SVG icon từ thư viện AXQ thành một file sprite duy nhất.
 *
 * Mỗi icon trở thành một <symbol id="{name}-{variant}"> bên trong
 * một <svg> ẩn. AXQIcon component sẽ tham chiếu bằng:
 *   <use href="/icons/axq-sprites.svg#{name}-{variant}" />
 *
 * Cấu trúc thư mục đầu vào mặc định:
 *   docs/asset/icon/bold/    → variant "bold"
 *   docs/asset/icon/linear/  → variant "linear"
 *
 * Cách chạy:
 *   node scripts/build-svg-sprites.mjs
 *   node scripts/build-svg-sprites.mjs --src docs/asset/icon --out public/icons/axq-sprites.svg
 *
 * Tùy chọn môi trường:
 *   ICON_SRC_DIR   (mặc định: docs/asset/icon)
 *   ICON_OUT_FILE  (mặc định: public/icons/axq-sprites.svg)
 */

import { readdir, readFile, mkdir, writeFile } from "node:fs/promises"
import { join, basename, extname } from "node:path"
import { parseArgs } from "node:util"

// ─── CLI args ─────────────────────────────────────────────────────────────────

const { values: args } = parseArgs({
  options: {
    src: { type: "string" },
    out: { type: "string" },
  },
  strict: false,
})

const WORKSPACE_ROOT = new URL("../", import.meta.url).pathname

const SRC_DIR  = args.src ?? process.env.ICON_SRC_DIR  ?? "docs/asset/icon"
const OUT_FILE = args.out ?? process.env.ICON_OUT_FILE ?? "public/icons/axq-sprites.svg"

const SRC_PATH = join(WORKSPACE_ROOT, SRC_DIR)
const OUT_PATH = join(WORKSPACE_ROOT, OUT_FILE)

// Map subfolder name → variant id used in the sprite symbol id
const VARIANT_MAP = {
  bold:   "bold",
  linear: "linear",
  // Alias mappings — add more as needed
  filled: "bold",
  outline: "linear",
}

// ─── SVG helpers ─────────────────────────────────────────────────────────────

/** Strip the outer <svg …> wrapper and return only the inner markup. */
function extractInnerSVG(svgContent) {
  // Remove XML declaration, comments, and DOCTYPE
  let s = svgContent.replace(/<\?xml[^>]*\?>/g, "").replace(/<!--[\s\S]*?-->/g, "").trim()

  // Capture the viewBox from the outer <svg> before stripping it
  const viewBoxMatch = s.match(/viewBox\s*=\s*["']([^"']+)["']/)
  const viewBox = viewBoxMatch ? viewBoxMatch[1] : "0 0 24 24"

  // Replace fill="#101426" / fill="black" / fill="#000000" → fill="currentColor"
  // so icons inherit color from CSS
  s = s
    .replace(/fill="#101426"/gi, 'fill="currentColor"')
    .replace(/fill="#000000"/gi, 'fill="currentColor"')
    .replace(/fill="black"/gi,   'fill="currentColor"')

  // Extract everything between the outermost <svg …> and </svg>
  const innerMatch = s.match(/<svg[^>]*>([\s\S]*)<\/svg>/i)
  const inner = innerMatch ? innerMatch[1].trim() : s

  return { viewBox, inner }
}

/** Build a <symbol> element for this icon. */
function buildSymbol(id, viewBox, inner) {
  return `  <symbol id="${id}" viewBox="${viewBox}">\n    ${inner}\n  </symbol>`
}

// ─── Main ─────────────────────────────────────────────────────────────────────

async function main() {
  console.log(`[axq-sprites] Source : ${SRC_PATH}`)
  console.log(`[axq-sprites] Output : ${OUT_PATH}`)

  let subfolders
  try {
    subfolders = await readdir(SRC_PATH, { withFileTypes: true })
  } catch {
    console.error(`[axq-sprites] ERROR: Source directory not found: ${SRC_PATH}`)
    process.exit(1)
  }

  const symbols = []
  let total = 0

  for (const entry of subfolders) {
    if (!entry.isDirectory()) continue

    const variant = VARIANT_MAP[entry.name.toLowerCase()]
    if (!variant) {
      console.warn(`[axq-sprites] Skipping unknown subfolder: ${entry.name}`)
      continue
    }

    const variantDir = join(SRC_PATH, entry.name)
    const files = (await readdir(variantDir)).filter(f => extname(f) === ".svg")

    for (const file of files) {
      const iconName = basename(file, ".svg")
      const id = `${iconName}-${variant}`
      const raw = await readFile(join(variantDir, file), "utf8")
      const { viewBox, inner } = extractInnerSVG(raw)
      symbols.push(buildSymbol(id, viewBox, inner))
      total++
    }

    console.log(`[axq-sprites] ${variant.padEnd(8)} — ${files.length} icons`)
  }

  if (total === 0) {
    console.warn("[axq-sprites] WARNING: No SVG files found. Output will be empty.")
  }

  const sprite = [
    `<?xml version="1.0" encoding="UTF-8"?>`,
    `<!-- AXQ Icon Sprite — ${total} icons — generated by scripts/build-svg-sprites.mjs -->`,
    `<!-- DO NOT EDIT MANUALLY -->`,
    `<svg xmlns="http://www.w3.org/2000/svg" style="display:none">`,
    ...symbols,
    `</svg>`,
  ].join("\n")

  await mkdir(new URL(OUT_PATH.replace(/\/[^/]+$/, "/"), "file://"), { recursive: true })
  await writeFile(OUT_PATH, sprite, "utf8")

  console.log(`[axq-sprites] ✓ Wrote ${total} symbols → ${OUT_PATH}`)
}

main().catch(err => {
  console.error("[axq-sprites] FATAL:", err)
  process.exit(1)
})
